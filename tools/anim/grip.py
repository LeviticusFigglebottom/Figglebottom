#!/usr/bin/env python3
"""Write the per-weapon-class grips (tools/anim/grips.json) into
data/anim/clip_meta.json as mounts "weapon@<class>" (pos + Godot YXZ euler).

The retargeted right hand's rest frame is the humanoid profile's: local X =
forward, Y = toward the fingers, Z = into the palm (measured on the Bearer).
Weapon meshes run blade +Y, edge +Z from the grip.
"""
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def norm(v):
    n = math.sqrt(sum(x * x for x in v))
    return [x / n for x in v]


def cross(a, b):
    return [a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0]]


def to_hand(v):   # [right, fwd, up] -> hand-bone local
    r, f, u = v
    return [f, r, -u]


def euler_yxz(cols):
    """Godot Basis.get_euler() (YXZ) in degrees for a basis given as columns."""
    r = [[cols[c][row] for c in range(3)] for row in range(3)]
    sx = -r[1][2]
    if abs(sx) > 0.9999:
        x = math.copysign(math.pi / 2, sx)
        y = math.atan2(-r[0][1], r[0][0]) if sx < 0 else math.atan2(r[0][1], r[0][0])
        z = 0.0
        if sx < 0:
            y = -math.atan2(r[0][1], r[0][0])
    else:
        x = math.asin(sx)
        y = math.atan2(r[0][2], r[2][2])
        z = math.atan2(r[1][0], r[1][1])
    return [round(math.degrees(a), 2) for a in (x, y, z)]


def main():
    grips = json.loads((ROOT / "tools/anim/grips.json").read_text())
    p = ROOT / "data/anim/clip_meta.json"
    meta = json.loads(p.read_text())
    for cls, g in grips.items():
        if cls.startswith("_"):
            continue
        for slot, bk, ek in (("weapon", "blade", "edge"), ("carry", "carry_blade", "carry_edge")):
            if bk not in g:
                continue
            y = norm(to_hand(g[bk]))
            e = to_hand(g[ek])
            d = sum(a * b for a, b in zip(y, e))
            z = norm([a - d * b for a, b in zip(e, y)])
            x = cross(y, z)
            key = f"{slot}@{cls}"
            meta["mounts"][key] = {"bone": "mixamorig_RightHand", "pos": g["pos"], "rot": euler_yxz([x, y, z]),
                                   "_note": "generated by tools/anim/grip.py from tools/anim/grips.json"}
            print(key, meta["mounts"][key]["rot"])
    p.write_text(json.dumps(meta, indent=1, ensure_ascii=False) + "\n")


if __name__ == "__main__":
    main()
